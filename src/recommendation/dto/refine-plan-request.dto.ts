import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { IsIn, IsInt, IsOptional, Max, Min } from 'class-validator';
import {
  REFINEMENT_ACTIONS,
  type RefinementAction,
} from '../../planning-engine/refinement/refinement';

/** "Más barato", "Cambiar esta parada"… applied to one plan of a search. */
export class RefinePlanRequestDto {
  @ApiProperty({ description: 'A plan generated by this request.' })
  @IsInt()
  @Min(1)
  planId: number;

  @ApiProperty({ enum: REFINEMENT_ACTIONS })
  @IsIn(REFINEMENT_ACTIONS)
  action: RefinementAction;

  @ApiPropertyOptional({
    description: 'Zero-based stop index (SWAP_STOP / REMOVE_STOP).',
  })
  @IsOptional()
  @IsInt()
  @Min(0)
  @Max(20)
  stopIndex?: number;
}
